package gocode

import (
	"fmt"
	"strings"

	"hikec-go/pkg/ast"
)

type sysvClass uint8

const (
	sysvNoClass sysvClass = iota
	sysvInteger
	sysvSSE
)

type amd64TypeInfo struct {
	size      int
	align     int
	class     sysvClass
	signed    bool
	aggregate bool
	classes   []sysvClass
	fields    []amd64Field
}

type amd64Field struct {
	name   string
	offset int
	info   amd64TypeInfo
}

type amd64TypeResolver struct {
	types       map[string]ast.TypeExpr
	pointerSize int
}

type amd64Argument struct {
	name        string
	info        amd64TypeInfo
	goOffset    int
	stacked     bool
	stackOffset int
	registers   []string
}

func generateLinuxAMD64Stubs(cfuncs []*ast.CFuncDecl, externs []*ast.ExternFuncDecl, typeDecls []*ast.TypeDecl, pkgName string) (string, error) {
	resolver := amd64TypeResolver{types: make(map[string]ast.TypeExpr), pointerSize: 8}
	for _, td := range typeDecls {
		if td != nil && td.Name != nil && td.Type != nil {
			resolver.types[td.Name.Value] = td.Type
			if pkgName != "" && strings.HasPrefix(td.Name.Value, pkgName+"_") {
				resolver.types[strings.TrimPrefix(td.Name.Value, pkgName+"_")] = td.Type
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by hikec go. DO NOT EDIT.\n")
	b.WriteString("#include \"textflag.h\"\n\n")

	for _, fn := range cfuncs {
		if fn == nil || fn.Name == nil {
			continue
		}
		if fn.IsVariadic {
			return "", fmt.Errorf("%s: variadic functions are not supported", fn.Name.Value)
		}
		if len(fn.ReturnTypes) > 1 {
			return "", fmt.Errorf("%s: multiple C ABI return values are not supported", fn.Name.Value)
		}

		targetName := "c_" + fn.Name.Value
		if fn.TargetCName != nil {
			targetName = fn.TargetCName.Value
		}

		params := make([]amd64Argument, len(fn.Params))
		goCursor := 0
		for i, param := range fn.Params {
			info, err := resolver.describe(param.Type, make(map[string]bool))
			if err != nil {
				return "", fmt.Errorf("%s parameter %d: %w", fn.Name.Value, i+1, err)
			}
			goCursor = alignUp(goCursor, info.align)
			params[i] = amd64Argument{
				name:     asmParamName(param, i),
				info:     info,
				goOffset: goCursor,
			}
			goCursor += info.size
		}

		var result *amd64TypeInfo
		resultOffset := goCursor
		if len(fn.ReturnTypes) == 1 {
			info, err := resolver.describe(fn.ReturnTypes[0], make(map[string]bool))
			if err != nil {
				return "", fmt.Errorf("%s return value: %w", fn.Name.Value, err)
			}
			if info.size > 16 {
				return "", fmt.Errorf("%s: aggregate return values larger than 16 bytes are not supported", fn.Name.Value)
			}
			resultOffset = alignUp(goCursor, info.align)
			goCursor = resultOffset + info.size
			result = &info
		}

		intRegisters := []string{"DI", "SI", "DX", "CX", "R8", "R9"}
		floatRegisters := []string{"X0", "X1", "X2", "X3", "X4", "X5", "X6", "X7"}
		intUsed, floatUsed := 0, 0
		stackSize := 0
		for i := range params {
			param := &params[i]
			info := param.info
			if info.size == 0 {
				continue
			}
			if info.size > 16 {
				param.stacked = true
			} else if hasSysvRegisters(info) {
				needInt, needFloat := countSysvRegisters(info)
				if intUsed+needInt <= len(intRegisters) && floatUsed+needFloat <= len(floatRegisters) {
					param.registers = make([]string, len(info.classes))
					for part, class := range info.classes {
						switch class {
						case sysvInteger:
							param.registers[part] = intRegisters[intUsed]
							intUsed++
						case sysvSSE:
							param.registers[part] = floatRegisters[floatUsed]
							floatUsed++
						}
					}
				} else {
					param.stacked = true
				}
			}
			if param.stacked {
				stackSize = alignUp(stackSize, min(info.align, 8))
				param.stackOffset = stackSize
				stackSize += alignUp(info.size, 8)
			}
		}

		// The dynamic adjustment aligns the outgoing SysV stack even when the
		// Go caller's stack alignment differs. Reserve a word for restoring it.
		callArea := alignUp(stackSize+8, 16)
		if callArea == 0 {
			callArea = 16
		}
		bookkeepingOffset := callArea - 8
		fmt.Fprintf(&b, "// %s (SysV AMD64)\n", fn.Name.Value)
		fmt.Fprintf(&b, "TEXT ·_hike_%s(SB), 0, $%d-%d\n", fn.Name.Value, callArea+16, goCursor)
		b.WriteString("    MOVQ SP, R11\n")
		b.WriteString("    ANDQ $15, R11\n")
		b.WriteString("    NEGQ R11\n")
		b.WriteString("    ANDQ $15, R11\n")
		b.WriteString("    ADDQ R11, SP\n")
		fmt.Fprintf(&b, "    MOVQ R11, %d(SP)\n", bookkeepingOffset)

		for _, param := range params {
			if param.info.size == 0 {
				continue
			}
			if param.stacked {
				emitSysVStackArgument(&b, param)
				continue
			}
			if hasSysvRegisters(param.info) {
				emitSysVRegisterArgument(&b, param)
			}
		}

		fmt.Fprintf(&b, "    CALL %s(SB)\n", targetName)
		b.WriteString(fmt.Sprintf("    MOVQ %d(SP), R11\n", bookkeepingOffset))
		b.WriteString("    SUBQ R11, SP\n")

		if result != nil {
			if result.aggregate {
				return "", fmt.Errorf("%s: aggregate return values are not supported", fn.Name.Value)
			}
			emitSysVReturn(&b, *result, resultOffset)
		}
		b.WriteString("    RET\n\n")
	}

	for _, fn := range externs {
		if target, ok := callbackPointerTarget(fn, cfuncs); ok {
			targetName := "c_" + target.Name.Value
			if target.TargetCName != nil {
				targetName = target.TargetCName.Value
			}
			fmt.Fprintf(&b, "// %s: address of %s\n", fn.Name.Value, target.Name.Value)
			fmt.Fprintf(&b, "TEXT ·%s(SB), NOSPLIT, $0-8\n", fn.Name.Value)
			fmt.Fprintf(&b, "    LEAQ %s(SB), AX\n", targetName)
			b.WriteString("    MOVQ AX, ret+0(FP)\n    RET\n\n")
		}
	}
	for _, fn := range cfuncs {
		targetName := "c_" + fn.Name.Value
		if fn.TargetCName != nil {
			targetName = fn.TargetCName.Value
		}
		fmt.Fprintf(&b, "// _hike_%sPtr: address of %s\n", fn.Name.Value, targetName)
		fmt.Fprintf(&b, "TEXT ·_hike_%sPtr(SB), NOSPLIT, $0-8\n", fn.Name.Value)
		fmt.Fprintf(&b, "    LEAQ %s(SB), AX\n", targetName)
		b.WriteString("    MOVQ AX, ret+0(FP)\n    RET\n\n")
	}

	return b.String(), nil
}

func (r amd64TypeResolver) describe(te ast.TypeExpr, visiting map[string]bool) (amd64TypeInfo, error) {
	if te == nil {
		return amd64TypeInfo{}, fmt.Errorf("missing type")
	}
	switch t := te.(type) {
	case *ast.PointerType:
		return scalarAMD64Type(r.pointerSize, r.pointerSize, sysvInteger, false), nil
	case *ast.NamedType:
		if t.Name == nil {
			return amd64TypeInfo{}, fmt.Errorf("unnamed type")
		}
		name := t.Name.Value
		if info, ok := scalarAMD64TypeByName(name, r.pointerSize); ok {
			return info, nil
		}
		underlying, ok := r.types[name]
		if !ok {
			return amd64TypeInfo{}, fmt.Errorf("unsupported type %q", name)
		}
		if visiting[name] {
			return amd64TypeInfo{}, fmt.Errorf("recursive value type %q", name)
		}
		visiting[name] = true
		info, err := r.describe(underlying, visiting)
		delete(visiting, name)
		return info, err
	case *ast.StructType:
		return r.describeStruct(t, visiting)
	default:
		return amd64TypeInfo{}, fmt.Errorf("unsupported type %q", te.TokenLiteral())
	}
}

func (r amd64TypeResolver) describeStruct(st *ast.StructType, visiting map[string]bool) (amd64TypeInfo, error) {
	info := amd64TypeInfo{align: 1, aggregate: true}
	for _, field := range st.Fields {
		if field == nil || field.Type == nil {
			continue
		}
		if field.Name == nil || field.Name.Value == "" {
			return amd64TypeInfo{}, fmt.Errorf("anonymous fields are not supported in Go assembly stubs")
		}
		fieldInfo, err := r.describe(field.Type, visiting)
		if err != nil {
			return amd64TypeInfo{}, err
		}
		info.align = max(info.align, fieldInfo.align)
		info.size = alignUp(info.size, fieldInfo.align)
		info.fields = append(info.fields, amd64Field{name: field.Name.Value, offset: info.size, info: fieldInfo})
		info.size += fieldInfo.size
	}
	info.size = alignUp(info.size, info.align)
	if info.size > 16 {
		return info, nil
	}
	info.classes = make([]sysvClass, (info.size+7)/8)
	for _, field := range info.fields {
		mergeAMD64Classes(info.classes, field.offset, field.info)
	}
	if len(info.classes) == 1 {
		info.class = info.classes[0]
	}
	return info, nil
}

func scalarAMD64Type(size, align int, class sysvClass, signed bool) amd64TypeInfo {
	return amd64TypeInfo{
		size:    size,
		align:   align,
		class:   class,
		signed:  signed,
		classes: []sysvClass{class},
	}
}

func scalarAMD64TypeByName(name string, pointerSize int) (amd64TypeInfo, bool) {
	switch name {
	case "bool", "uint8", "byte":
		return scalarAMD64Type(1, 1, sysvInteger, false), true
	case "int8":
		return scalarAMD64Type(1, 1, sysvInteger, true), true
	case "uint16":
		return scalarAMD64Type(2, 2, sysvInteger, false), true
	case "int16":
		return scalarAMD64Type(2, 2, sysvInteger, true), true
	case "uint32":
		return scalarAMD64Type(4, 4, sysvInteger, false), true
	case "int32", "rune":
		return scalarAMD64Type(4, 4, sysvInteger, true), true
	case "cstring", "uint64", "uintptr", "uint":
		return scalarAMD64Type(pointerSize, pointerSize, sysvInteger, false), true
	case "int64", "int":
		return scalarAMD64Type(pointerSize, pointerSize, sysvInteger, true), true
	case "float32":
		return scalarAMD64Type(4, 4, sysvSSE, false), true
	case "float64":
		return scalarAMD64Type(8, 8, sysvSSE, false), true
	default:
		return amd64TypeInfo{}, false
	}
}

func mergeAMD64Classes(dst []sysvClass, offset int, src amd64TypeInfo) {
	for i, class := range src.classes {
		start := offset + i*8
		end := min(offset+src.size, start+8)
		if class == sysvNoClass || end <= start {
			continue
		}
		for index := start / 8; index <= (end-1)/8; index++ {
			if index < len(dst) && (dst[index] == sysvNoClass || class == sysvInteger) {
				dst[index] = class
			}
		}
	}
}

func countSysvRegisters(info amd64TypeInfo) (int, int) {
	ints, floats := 0, 0
	for _, class := range info.classes {
		switch class {
		case sysvInteger:
			ints++
		case sysvSSE:
			floats++
		}
	}
	return ints, floats
}

func hasSysvRegisters(info amd64TypeInfo) bool {
	for _, class := range info.classes {
		if class != sysvNoClass {
			return true
		}
	}
	return false
}

func emitSysVRegisterArgument(b *strings.Builder, arg amd64Argument) {
	if !arg.info.aggregate && len(arg.registers) == 1 && arg.info.class != sysvNoClass {
		reg := arg.registers[0]
		src := fmt.Sprintf("%s+%d(FP)", arg.name, arg.goOffset)
		switch arg.info.class {
		case sysvInteger:
			emitIntegerRegisterLoad(b, src, reg, arg.info)
		case sysvSSE:
			if arg.info.size == 4 {
				fmt.Fprintf(b, "    MOVSS %s, %s\n", src, reg)
			} else {
				fmt.Fprintf(b, "    MOVSD %s, %s\n", src, reg)
			}
		}
		return
	}

	for part, reg := range arg.registers {
		if reg == "" {
			continue
		}
		offset := part * 8
		emitAggregateRegisterPiece(b, arg.name, arg.goOffset, arg.info, offset, min(8, arg.info.size-offset), reg)
	}
}

func emitIntegerRegisterLoad(b *strings.Builder, src, reg string, info amd64TypeInfo) {
	switch info.size {
	case 1:
		op := "MOVBQZX"
		if info.signed {
			op = "MOVBQSX"
		}
		fmt.Fprintf(b, "    %s %s, %s\n", op, src, reg)
	case 2:
		op := "MOVWQZX"
		if info.signed {
			op = "MOVWQSX"
		}
		fmt.Fprintf(b, "    %s %s, %s\n", op, src, reg)
	case 4:
		op := "MOVLQZX"
		if info.signed {
			op = "MOVLQSX"
		}
		fmt.Fprintf(b, "    %s %s, %s\n", op, src, reg)
	default:
		fmt.Fprintf(b, "    MOVQ %s, %s\n", src, reg)
	}
}

func emitAggregateRegisterPiece(b *strings.Builder, argName string, goOffset int, info amd64TypeInfo, pieceOffset, pieceSize int, reg string) {
	fmt.Fprintf(b, "    MOVQ $0, AX\n")
	emitAggregatePieceFields(b, argName, goOffset, info, pieceOffset, 0, pieceSize)
	fmt.Fprintf(b, "    MOVQ AX, %s\n", reg)
}

func emitAggregatePieceFields(b *strings.Builder, prefix string, goOffset int, info amd64TypeInfo, pieceOffset, currentOffset, pieceSize int) {
	for _, field := range info.fields {
		fieldOffset := currentOffset + field.offset
		fieldEnd := fieldOffset + field.info.size
		if fieldEnd <= pieceOffset || fieldOffset >= pieceOffset+pieceSize {
			continue
		}
		fieldName := prefix + "_" + field.name
		if field.info.aggregate {
			emitAggregatePieceFields(b, fieldName, goOffset+field.offset, field.info, pieceOffset, fieldOffset, pieceSize)
			continue
		}
		source := fmt.Sprintf("%s+%d(FP)", fieldName, goOffset+field.offset)
		relative := fieldOffset - pieceOffset
		if field.info.class == sysvSSE {
			if field.info.size == 4 {
				fmt.Fprintf(b, "    PXOR X15, X15\n")
				fmt.Fprintf(b, "    MOVSS %s, X15\n", source)
				fmt.Fprintf(b, "    MOVQ X15, R10\n")
			} else {
				fmt.Fprintf(b, "    MOVSD %s, X15\n", source)
				fmt.Fprintf(b, "    MOVQ X15, R10\n")
			}
		} else {
			op := "MOVQ"
			switch field.info.size {
			case 1:
				op = "MOVBQZX"
			case 2:
				op = "MOVWQZX"
			case 4:
				op = "MOVLQZX"
			}
			fmt.Fprintf(b, "    %s %s, R10\n", op, source)
		}
		if relative != 0 {
			fmt.Fprintf(b, "    SHLQ $%d, R10\n", relative*8)
		}
		fmt.Fprintf(b, "    ORQ R10, AX\n")
	}
}

func emitSysVStackArgument(b *strings.Builder, arg amd64Argument) {
	if !arg.info.aggregate {
		src := fmt.Sprintf("%s+%d(FP)", arg.name, arg.goOffset)
		emitTypedCopyToStack(b, src, arg.stackOffset, arg.info)
		return
	}
	emitAggregateStackFields(b, arg.name, arg.goOffset, arg.stackOffset, arg.info)
}

func emitAggregateStackFields(b *strings.Builder, prefix string, goOffset, stackOffset int, info amd64TypeInfo) {
	for _, field := range info.fields {
		fieldName := prefix + "_" + field.name
		if field.info.aggregate {
			emitAggregateStackFields(b, fieldName, goOffset+field.offset, stackOffset+field.offset, field.info)
			continue
		}
		src := fmt.Sprintf("%s+%d(FP)", fieldName, goOffset+field.offset)
		emitTypedCopyToStack(b, src, stackOffset+field.offset, field.info)
	}
}

func emitTypedCopyToStack(b *strings.Builder, src string, dstOffset int, info amd64TypeInfo) {
	if info.class == sysvSSE {
		if info.size == 4 {
			fmt.Fprintf(b, "    MOVSS %s, X15\n", src)
			fmt.Fprintf(b, "    MOVSS X15, %d(SP)\n", dstOffset)
		} else {
			fmt.Fprintf(b, "    MOVSD %s, X15\n", src)
			fmt.Fprintf(b, "    MOVSD X15, %d(SP)\n", dstOffset)
		}
		return
	}
	emitCopyToStack(b, src, dstOffset, info.size)
}

func emitCopyToStack(b *strings.Builder, src string, dstOffset, size int) {
	offset := 0
	for size-offset >= 8 {
		fmt.Fprintf(b, "    MOVQ %s, AX\n", addAsmOffset(src, offset))
		fmt.Fprintf(b, "    MOVQ AX, %d(SP)\n", dstOffset+offset)
		offset += 8
	}
	if size-offset >= 4 {
		fmt.Fprintf(b, "    MOVLQZX %s, AX\n", addAsmOffset(src, offset))
		fmt.Fprintf(b, "    MOVL AX, %d(SP)\n", dstOffset+offset)
		offset += 4
	}
	if size-offset >= 2 {
		fmt.Fprintf(b, "    MOVWQZX %s, AX\n", addAsmOffset(src, offset))
		fmt.Fprintf(b, "    MOVW AX, %d(SP)\n", dstOffset+offset)
		offset += 2
	}
	if size-offset == 1 {
		fmt.Fprintf(b, "    MOVBQZX %s, AX\n", addAsmOffset(src, offset))
		fmt.Fprintf(b, "    MOVB AX, %d(SP)\n", dstOffset+offset)
	}
}

func emitSysVReturn(b *strings.Builder, info amd64TypeInfo, goOffset int) {
	if !info.aggregate && (info.class == sysvInteger || info.class == sysvSSE) {
		dst := fmt.Sprintf("ret+%d(FP)", goOffset)
		switch info.class {
		case sysvInteger:
			emitIntegerReturnStore(b, "AX", dst, info.size)
		case sysvSSE:
			if info.size == 4 {
				fmt.Fprintf(b, "    MOVSS X0, %s\n", dst)
			} else {
				fmt.Fprintf(b, "    MOVSD X0, %s\n", dst)
			}
		}
		return
	}

	intRegisters := []string{"AX", "DX"}
	floatRegisters := []string{"X0", "X1"}
	intUsed, floatUsed := 0, 0
	for part, class := range info.classes {
		offset := part * 8
		size := min(8, info.size-offset)
		dst := fmt.Sprintf("%d(FP)", goOffset+offset)
		switch class {
		case sysvInteger:
			emitIntegerReturnStore(b, intRegisters[intUsed], dst, size)
			intUsed++
		case sysvSSE:
			if size == 4 {
				fmt.Fprintf(b, "    MOVSS %s, %s\n", floatRegisters[floatUsed], dst)
			} else {
				fmt.Fprintf(b, "    MOVQ %s, %s\n", floatRegisters[floatUsed], dst)
			}
			floatUsed++
		}
	}
}

func emitIntegerReturnStore(b *strings.Builder, reg, dst string, size int) {
	switch size {
	case 1:
		fmt.Fprintf(b, "    MOVB %s, %s\n", reg, dst)
	case 2:
		fmt.Fprintf(b, "    MOVW %s, %s\n", reg, dst)
	case 4:
		fmt.Fprintf(b, "    MOVL %s, %s\n", reg, dst)
	default:
		fmt.Fprintf(b, "    MOVQ %s, %s\n", reg, dst)
	}
}

func addAsmOffset(src string, offset int) string {
	if offset == 0 {
		return src
	}
	if strings.HasSuffix(src, "(FP)") {
		return strings.TrimSuffix(src, "(FP)") + fmt.Sprintf("+%d(FP)", offset)
	}
	return src
}

func alignUp(value, alignment int) int {
	if alignment <= 1 {
		return value
	}
	return (value + alignment - 1) &^ (alignment - 1)
}
