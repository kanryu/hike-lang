package gocode

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"hikec-go/pkg/ast"
)

// GenerateGoDeclarations は *.go.hike から Go コンパイラ用の *.go ラッパー・宣言ファイルを生成します。
func GenerateGoDeclarations(destGoPath string, pkgName string, decls []ast.Decl, verbose bool) error {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by hikec. DO NOT EDIT.\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", pkgName))

	needsUnsafe := true // SliceData, String, unsafe.Pointer 等で基本的に必要
	var wrapperFuncs []string
	var nativeDecls []string

	// CFuncDecl のみを抽出
	var cfuncs []*ast.CFuncDecl
	for _, decl := range decls {
		if cfn, ok := decl.(*ast.CFuncDecl); ok {
			cfuncs = append(cfuncs, cfn)
		}
	}

	// 1. 公開 Go ラッパー関数の生成（大文字始まりのエクスポート関数のみ）
	for _, cfn := range cfuncs {
		fnName := cfn.Name.Value
		if !isExported(fnName) {
			continue
		}

		wrapper := generateWrapperFunc(cfn)
		if wrapper != "" {
			wrapperFuncs = append(wrapperFuncs, wrapper)
		}
	}

	// 2. ネイティブリンク宣言の生成（stub.s 結合用）
	for _, cfn := range cfuncs {
		nativeDecl := generateNativeDecl(cfn)
		nativeDecls = append(nativeDecls, nativeDecl)
	}

	if needsUnsafe {
		buf.WriteString("import \"unsafe\"\n\n")
	}
	buf.WriteString(`func hikeCStringToString(ptr *byte) string {
	if ptr == nil {
		return ""
	}
	n := 0
	for *(*byte)(unsafe.Add(unsafe.Pointer(ptr), uintptr(n))) != 0 {
		n++
	}
	return string(unsafe.Slice(ptr, n))
}

`)

	// ラッパー関数群の出力
	for _, w := range wrapperFuncs {
		buf.WriteString(w + "\n")
	}

	// ネイティブ宣言群の出力
	buf.WriteString("// -----------------------------------------------------------------------------\n")
	buf.WriteString("// ネイティブリンク宣言（stub.s のアセンブリを経由して .syso と結合）\n")
	buf.WriteString("// -----------------------------------------------------------------------------\n")
	for _, nd := range nativeDecls {
		buf.WriteString(nd + "\n")
	}

	if verbose {
		fmt.Printf("[hikec go] Emitting Go declarations -> %s\n", filepath.Base(destGoPath))
	}

	return os.WriteFile(destGoPath, buf.Bytes(), 0644)
}

// generateWrapperFunc は CFuncDecl から Go フレンドリーなラッパー関数を合成します。
func generateWrapperFunc(cfn *ast.CFuncDecl) string {
	fnName := cfn.Name.Value
	var params []string
	var callArgs []string
	var conversions []string
	for _, p := range cfn.Params {
		name := p.Name.Value
		if isCStringType(p.Type) {
			params = append(params, name+" string")
			bufName := name + "Bytes"
			conversions = append(conversions,
				fmt.Sprintf("%s := append([]byte(%s), 0)", bufName, name),
			)
			callArgs = append(callArgs, "&"+bufName+"[0]")
			if isCStringLengthPair(cfn.Params, name) {
				callArgs = append(callArgs, "len("+bufName+")-1")
			}
			continue
		}
		if isHiddenCStringLength(cfn.Params, p) {
			continue
		}
		goType, _ := typeExprToGoType(p.Type, false)
		params = append(params, name+" "+goType)
		callArgs = append(callArgs, name)
	}

	returnType := ""
	if len(cfn.ReturnTypes) == 1 {
		if isCStringType(cfn.ReturnTypes[0]) {
			returnType = " string"
		} else {
			goType, _ := typeExprToGoType(cfn.ReturnTypes[0], true)
			returnType = " " + goType
		}
	} else if len(cfn.ReturnTypes) > 1 {
		var returns []string
		for _, rt := range cfn.ReturnTypes {
			goType, _ := typeExprToGoType(rt, true)
			returns = append(returns, goType)
		}
		returnType = " (" + strings.Join(returns, ", ") + ")"
	}

	call := fmt.Sprintf("_hike_%s(%s)", fnName, strings.Join(callArgs, ", "))
	var body []string
	body = append(body, conversions...)
	if len(cfn.ReturnTypes) == 1 && isCStringType(cfn.ReturnTypes[0]) {
		body = append(body, "return hikeCStringToString("+call+")")
	} else if len(cfn.ReturnTypes) > 0 {
		body = append(body, "return "+call)
	} else {
		body = append(body, call)
	}

	return fmt.Sprintf("// %s: generated from the Hike cfunc signature\nfunc %s(%s)%s {\n\t%s\n}\n",
		fnName, fnName, strings.Join(params, ", "), returnType, strings.Join(body, "\n\t"))
}

// generateNativeDecl は stub.s 接続用の _hike_xxx 宣言を合成します。
func generateNativeDecl(cfn *ast.CFuncDecl) string {
	fnName := cfn.Name.Value
	var params []string

	for i := 0; i < len(cfn.Params); i++ {
		p := cfn.Params[i]

		if isCStringType(p.Type) {
			params = append(params, fmt.Sprintf("%s *byte", p.Name.Value))
			continue
		}
		// The length remains part of the native ABI. It is hidden only by
		// the public wrapper for the conventional cstring/length pair.

		goType, _ := typeExprToGoType(p.Type, false)
		params = append(params, fmt.Sprintf("%s %s", p.Name.Value, goType))
	}

	resStr := ""
	if len(cfn.ReturnTypes) == 1 {
		goRet, _ := typeExprToNativeGoType(cfn.ReturnTypes[0])
		resStr = " " + goRet
	} else if len(cfn.ReturnTypes) > 1 {
		var rets []string
		for _, rt := range cfn.ReturnTypes {
			t, _ := typeExprToNativeGoType(rt)
			rets = append(rets, t)
		}
		resStr = " (" + strings.Join(rets, ", ") + ")"
	}

	return fmt.Sprintf("func _hike_%s(%s)%s", fnName, strings.Join(params, ", "), resStr)
}

func isCStringLengthPair(params []*ast.ParamDecl, cstringName string) bool {
	for i, p := range params {
		if p.Name.Value != cstringName || i+1 >= len(params) {
			continue
		}
		next := params[i+1]
		if !isIntType(next.Type) {
			return false
		}
		base := strings.TrimSuffix(cstringName, "_ptr")
		return next.Name.Value == "len" || next.Name.Value == "length" || next.Name.Value == base+"_len"
	}
	return false
}

func isHiddenCStringLength(params []*ast.ParamDecl, p *ast.ParamDecl) bool {
	for i, candidate := range params {
		if candidate != p || i == 0 {
			continue
		}
		prev := params[i-1]
		return isIntType(p.Type) && isCStringType(prev.Type) && isCStringLengthPair(params, prev.Name.Value)
	}
	return false
}

func typeExprToNativeGoType(te ast.TypeExpr) (string, bool) {
	if isCStringType(te) {
		return "*byte", false
	}
	return typeExprToGoType(te, true)
}

func isExported(name string) bool {
	if len(name) == 0 {
		return false
	}
	return unicode.IsUpper(rune(name[0]))
}

func isPointerType(te ast.TypeExpr) bool {
	if te == nil {
		return false
	}
	_, ok := te.(*ast.PointerType)
	return ok || strings.HasPrefix(te.TokenLiteral(), "*")
}

func isCStringType(te ast.TypeExpr) bool {
	if te == nil {
		return false
	}
	if nt, ok := te.(*ast.NamedType); ok {
		return nt.Name.Value == "cstring"
	}
	return te.TokenLiteral() == "cstring"
}

func isIntType(te ast.TypeExpr) bool {
	if te == nil {
		return false
	}
	if nt, ok := te.(*ast.NamedType); ok {
		return nt.Name.Value == "int"
	}
	return te.TokenLiteral() == "int"
}

func typeExprToGoType(te ast.TypeExpr, isReturn bool) (string, bool) {
	if te == nil {
		return "", false
	}

	switch t := te.(type) {
	case *ast.NamedType:
		name := t.Name.Value
		if name == "cstring" {
			if isReturn {
				return "unsafe.Pointer", true
			}
			return "string", false
		}
		return name, false

	case *ast.PointerType:
		baseName, isUnsafe := typeExprToGoType(t.Base, isReturn)
		if baseName == "void" {
			return "unsafe.Pointer", true
		}
		return "*" + baseName, isUnsafe

	default:
		lit := te.TokenLiteral()
		if lit == "cstring" {
			if isReturn {
				return "unsafe.Pointer", true
			}
			return "string", false
		}
		return lit, false
	}
}
